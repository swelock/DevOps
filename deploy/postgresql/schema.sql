CREATE TABLE IF NOT EXISTS buildings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE CHECK(length(btrim(name)) BETWEEN 1 AND 100),
    address VARCHAR(250) NOT NULL CHECK(length(btrim(address)) BETWEEN 1 AND 250)
);

CREATE TABLE IF NOT EXISTS departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE CHECK(length(btrim(name)) BETWEEN 1 AND 100)
);

CREATE TABLE IF NOT EXISTS rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_id BIGINT NOT NULL REFERENCES buildings(id) ON DELETE RESTRICT,
    department_id BIGINT NOT NULL REFERENCES departments(id) ON DELETE RESTRICT,
    number VARCHAR(30) NOT NULL CHECK(length(btrim(number)) BETWEEN 1 AND 30),
    area DOUBLE PRECISION NOT NULL CHECK(area > 0 AND area <= 100000),
    height DOUBLE PRECISION NOT NULL CHECK(height > 0 AND height <= 100),
    UNIQUE(building_id, number)
);
